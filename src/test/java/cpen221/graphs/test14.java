    @Test
    public void testComplexGraphEdges() {
        Vertex[] vertices = new Vertex[5];
        for (int i = 0; i < 5; i++) {
            vertices[i] = new Vertex(i);
        }

        List<Edge<Vertex>> edges = new ArrayList<>();
        edges.add(new Edge<>(vertices[0], vertices[1], 1.0));
        edges.add(new Edge<>(vertices[1], vertices[2], 2.0));
        edges.add(new Edge<>(vertices[2], vertices[3], 3.0));
        edges.add(new Edge<>(vertices[3], vertices[4], 4.0));

        for (int i = 0; i < edges.size() - 1; i++) {
            assertTrue(edges.get(i).intersects(edges.get(i + 1)));
        }

        double totalLength = 0;
        for (Edge<Vertex> e : edges) {
            totalLength += e.length();
        }
        assertEquals(10.0, totalLength);
    }

