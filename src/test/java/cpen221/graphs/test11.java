    @Test
    public void testLargeLinearPath() {
        // Create a long linear path
        int size = 100;
        Vertex[] vertices = new Vertex[size];
        for (int i = 0; i < size; i++) {
            vertices[i] = new Vertex(i);
            graph.addVertex(vertices[i]);
        }

        for (int i = 0; i < size - 1; i++) {
            graph.addEdge(new Edge<>(vertices[i], vertices[i+1], 1.0));
        }

        // Diameter should be 99 (from one end to the other)
        assertEquals(99.0, Algorithms.diameter(graph, PathCostType.SUM_EDGES));

        // Path should work correctly
        List<Vertex> path = Algorithms.minimumCostPath(
                graph, vertices[0], vertices[size-1], PathCostType.SUM_EDGES
        );
        assertEquals(size, path.size());
    }

    @Test
    public void testLargeDenseGraph() {
        // Create a nearly-complete graph
        int size = 20;
        Vertex[] vertices = new Vertex[size];
        for (int i = 0; i < size; i++) {
            vertices[i] = new Vertex(i);
            graph.addVertex(vertices[i]);
        }

        // Add edges between most pairs
        for (int i = 0; i < size; i++) {
            for (int j = i + 1; j < Math.min(i + 5, size); j++) {
                graph.addEdge(new Edge<>(vertices[i], vertices[j], 1.0));
            }
        }

        double dia = Algorithms.diameter(graph, PathCostType.SUM_EDGES);
        assertTrue(dia > 0);

        Vertex center = Algorithms.center(graph, PathCostType.SUM_EDGES);
        assertNotNull(center);
    }
