    @Test
    public void testImmutability() {
        Vertex v0 = new Vertex(0);
        Vertex v1 = new Vertex(1);
        vertices.add(v0);
        vertices.add(v1);

        Edge<Vertex> e = new Edge<>(v0, v1, 1.0);
        edges.add(e);

        AdjacencyMatrixGraph<Vertex, Edge<Vertex>> graph = new AdjacencyMatrixGraph<>(vertices, edges);

        // Try to modify original sets
        Vertex v2 = new Vertex(2);
        vertices.add(v2);
        edges.add(new Edge<>(v1, v2, 1.0));

        // Graph should be unchanged
        assertEquals(2, graph.getVertices().size());
        assertEquals(1, graph.getEdges().size());
        assertFalse(graph.hasVertex(v2));
    }
