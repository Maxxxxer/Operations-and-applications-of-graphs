package cpen221.graphs.graph;

import java.util.*;
/**
 * Mutable undirected graph implementation using adjacency lists.
 *
 * <p>This implementation uses a combination of:
 * <ul>
 *   <li>A Set to store all vertices</li>
 *   <li>A Set to store all edges</li>
 *   <li>A Map of Maps (adjacency list) to store adjacency information: each vertex maps to a map of its neighbors</li>
 * </ul>
 *
 * <p><b>Time Complexity:</b>
 * <ul>
 *   <li>addVertex: O(1) average case</li>
 *   <li>addEdge: O(1) average case</li>
 *   <li>hasEdge: O(1) average case</li>
 *   <li>removeVertex: O(degree of vertex)</li>
 *   <li>getNeighbours: O(degree of vertex)</li>
 * </ul>
 *
 * <p><b>Space Complexity:</b> O(V + E) where V is the number of vertices and E is the number of edges.
 *
 * <p>This implementation is suitable for sparse graphs where the number of edges is much smaller
 * than the number of possible edges between all vertices.
 *
 * @param <V> the type of vertices in the graph, must extend Vertex
 * @param <E> the type of edges in the graph, must extend Edge&lt;V&gt;
 * @author CPEN 221
 * @version 1.0
 */
//the javadoc above was generated by AI, I have looked over it to make sure that it make sense and have no mistakes

public class AdjacencyListGraph<V extends Vertex, E extends Edge<V>> implements Graph<V,E> {

    private final Set<V> vertice = new HashSet<>();
    private final Set<E> edge = new HashSet<>();
    private final Map<V, Map<V, E>> adj = new HashMap<>();

    @Override
    public boolean addVertex(V v) {
        Objects.requireNonNull(v, "vertex");
        if (vertice.contains(v)) return false;
        vertice.add(v);
        adj.put(v, new HashMap<>());
        return true;
    }

    @Override
    public boolean hasVertex(V v) { return vertice.contains(v); }

    @Override
    public boolean addEdge(E e) {
        Objects.requireNonNull(e, "edge");
        V a1 = e.v1(), b = e.v2();
        if (!vertice.contains(a1) || !vertice.contains(b)) return false;
        Map<V,E> ma = adj.get(a1), mb = adj.get(b);
        if (ma.containsKey(b)) return false; // duplicate between endpoints
        ma.put(b, e); mb.put(a1, e);
        edge.add(e);
        return true;
    }

    @Override
    public boolean hasEdge(E e) { return edge.contains(e); }

    @Override
    public boolean hasEdge(V v1, V v2) {
        Map<V,E> m1 = adj.get(v1);
        return m1 != null && m1.containsKey(v2);
    }

    @Override
    public double edgeLength(V v1, V v2) {
        E e1 = getEdge(v1, v2);
        if (e1 == null) throw new NoSuchElementException("no such edge");
        return e1.length();
    }

    @Override
    public double edgeLengthSum() {
        double sum1 = 0.0;
        for (E e2 : edge) sum1 += e2.length();
        return sum1;
    }

    @Override
    public boolean removeEdge(E e) {
        if (e == null || !edge.contains(e)) return false;
        V a2 = e.v1(), b1 = e.v2();
        adj.getOrDefault(a2, Collections.emptyMap()).remove(b1);
        adj.getOrDefault(b1, Collections.emptyMap()).remove(a2);
        edge.remove(e);
        return true;
    }

    @Override
    public boolean removeEdge(V v1, V v2) {
        E e3 = getEdge(v1, v2);
        return (e3 != null) && removeEdge(e3);
    }

    @Override
    public boolean removeVertex(V v) {
        if (!vertice.contains(v)) return false;
        for (V nb : new ArrayList<>(adj.get(v).keySet())) {
            E e4 = adj.get(v).get(nb);
            adj.get(nb).remove(v);
            edge.remove(e4);
        }
        adj.remove(v);
        vertice.remove(v);
        return true;
    }

    @Override
    public E getEdge(V v1, V v2) {
        Map<V,E> m2 = adj.get(v1);
        return m2 == null ? null : m2.get(v2);
    }

    @Override
    public Set<V> getVertices() { return new HashSet<>(vertice); }

    @Override
    public Set<E> getEdges() { return new HashSet<>(edge); }

    @Override
    public Set<E> getEdges(V v) {
        Map<V,E> m3 = adj.get(v);
        return m3 == null ? Collections.emptySet() : new HashSet<>(m3.values());
    }

    @Override
    public Map<V, E> getNeighbours(V v) {
        Map<V,E> m4 = adj.get(v);
        return m4 == null ? Collections.emptyMap() : new HashMap<>(m4);
    }

    @Override
    public double pathCost(List<V> path, PathCostType costType) {
        return Algorithms.pathCost(this, path, costType);
    }

    @Override
    public List<V> minimumCostPath(V source, V sink, PathCostType costType) {
        return Algorithms.minimumCostPath(this, source, sink, costType);
    }

    @Override
    public double getDiameter(PathCostType costType) {
        return Algorithms.diameter(this, costType);
    }

    @Override
    public V getCenter(PathCostType costType) {
        return Algorithms.center(this, costType);
    }


    @Override
    public Set<Set<V>> getComponents() {
        throw new UnsupportedOperationException("task not implemented");
    }
}

