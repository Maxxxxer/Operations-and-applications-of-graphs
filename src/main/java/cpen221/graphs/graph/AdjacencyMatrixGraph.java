public class AdjacencyMatrixGraph<V extends Vertex, E extends Edge<V>> implements Graph<V,E> {
    private final Set<V> vertices;
    private final Set<E> edges;
    private final Map<V, Integer> index;
    private final Edge<V>[][] matrix;

    @SuppressWarnings("unchecked")
    public AdjacencyMatrixGraph(Set<V> vs, Set<E> es) {
        this.vertices = new HashSet<>(vs);
        this.edges = new HashSet<>();
        this.index = new HashMap<>();
        int n1 = vertices.size();
        int i1 = 0;
        for (V v : vertices) index.put(v, i1++);
        this.matrix = (Edge<V>[][]) new Edge[n1][n1];

        for (E e1 : es) {
            V a = e1.v1(), b = e1.v2();
            if (!vertices.contains(a) || !vertices.contains(b)) continue;
            int ia = index.get(a), ib = index.get(b);
            if (matrix[ia][ib] == null) {
                matrix[ia][ib] = e1;
                matrix[ib][ia] = e1;
                this.edges.add(e1);
            }
        }
    }


    @Override public boolean addVertex(V v){ throw new UnsupportedOperationException("is immutable"); }

    @Override public boolean addEdge(E e){ throw new UnsupportedOperationException("is immutable"); }

    @Override public boolean removeEdge(E e){ throw new UnsupportedOperationException("is immutable"); }

    @Override public boolean removeEdge(V v1,V v2){ throw new UnsupportedOperationException("isimmutable"); }

    @Override public boolean removeVertex(V v){ throw new UnsupportedOperationException("is immutable"); }

    @Override public boolean hasVertex(V v) { return vertices.contains(v); }

    @Override public boolean hasEdge(E e) { return edges.contains(e); }

    @Override
    public boolean hasEdge(V v1, V v2) {
        Integer i1 = index.get(v1), j1 = index.get(v2);
        return (i1 != null) && (j1 != null) && (matrix[i1][j1] != null);
    }

    @Override
    public double edgeLength(V v1, V v2) {
        E e1 = getEdge(v1, v2);
        if (e1 == null)
            throw new NoSuchElementException("edge is null");
        return e1.length();
    }

    @Override
    public double edgeLengthSum() {
        double sum = 0.0;
        for (E e : edges) {
            sum = sum + e.length();
        }
        return sum;
    }

    @SuppressWarnings("unchecked")
    @Override
    public E getEdge(V v1, V v2) {
        Integer i = index.get(v1), j = index.get(v2);
        if (i == null || j == null)
            return null;
        return (E) matrix[i][j];
    }

    @Override public Set<V> getVertices() { return new HashSet<>(vertices); }

    @Override public Set<E> getEdges() { return new HashSet<>(edges); }

    @Override
    public Set<E> getEdges(V v) {
        Integer i = index.get(v);
        if (i == null)
            return Collections.emptySet();
        Set<E> result = new HashSet<>();
        for (int j = 0; j < matrix.length; j++) {
            @SuppressWarnings("unchecked")
            E e = (E) matrix[i][j];
            if (e != null) result.add(e);
        }
        return result;
    }

    @Override
    public Map<V, E> getNeighbours(V v) {
        Integer i1 = index.get(v);
        if (i1 == null)
            return Collections.emptyMap();
        Map<V,E> result = new HashMap<>();
        for (Map.Entry<V,Integer> ent : index.entrySet()) {
            int j1 = ent.getValue();
            @SuppressWarnings("unchecked")
            E e = (E) matrix[i1][j1];
            if (e != null) result.put(ent.getKey(), e);
        }
        return result;
    }

   //task 3and 4
    @Override
    public double pathCost(List<V> path, PathCostType costType) {
        return Algorithms.pathCost(this, path, costType);
    }

    @Override
    public List<V> minimumCostPath(V source, V sink, PathCostType costType) {
        return Algorithms.minimumCostPath(this, source, sink, costType);
    }

    @Override
    public double getDiameter(PathCostType costType) {
        return Algorithms.diameter(this, costType);
    }

    @Override
    public V getCenter(PathCostType costType) {
        return Algorithms.center(this, costType);
    }

    @Override
    public Set<Set<V>> getComponents() {
        throw new UnsupportedOperationException("not implemented");
    }
}

