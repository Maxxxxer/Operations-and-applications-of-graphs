package cpen221.graphs.graph;

import java.util.*;

/**
 * Immutable undirected graph implementation using an adjacency matrix.
 *
 * <p>This implementation:
 * <ul>
 *   <li>Uses a 2D array to store edges in a symmetric adjacency matrix</li>
 *   <li>Maps each vertex to its index in the matrix</li>
 *   <li>Is immutable - all mutation methods throw UnsupportedOperationException</li>
 * </ul>
 *
 * <p><b>Time Complexity:</b>
 * <ul>
 *   <li>hasEdge: O(1)</li>
 *   <li>getEdge: O(1)</li>
 *   <li>addVertex/removeVertex/addEdge/removeEdge: O(1) - throw UnsupportedOperationException</li>
 *   <li>getNeighbours: O(V) where V is the number of vertices</li>
 * </ul>
 *
 * <p><b>Space Complexity:</b> O(V²) where V is the number of vertices, regardless of the number of edges.
 * This makes it suitable for dense graphs but wasteful for sparse graphs.
 *
 * <p><b>Construction Note:</b>
 * Edges with missing endpoints or duplicate edges are silently ignored during construction.
 * The graph is immutable after construction.
 *
 * <p>Task 5 (connected components) is not implemented.
 *
 * @param <V> the type of vertices in the graph, must extend Vertex
 * @param <E> the type of edges in the graph, must extend Edge&lt;V&gt;
 * @author CPEN 221
 * @version 1.0
 */

